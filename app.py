def _load_model() -> object | None:
    """Load the trained pipeline from disk; return None if not found."""
    if not BEST_MODEL_PATH.exists():
        logger.warning(
            "Model file not found at %s. Run `python -m src.pipeline.train` first.",
            BEST_MODEL_PATH,
        )
        return None
    model = joblib.load(BEST_MODEL_PATH)
    logger.info("Model loaded from %s", BEST_MODEL_PATH)
    return model


