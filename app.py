def predict_tab_handler(
    file_obj,
    use_sample: bool,
) -> tuple[pd.DataFrame, str, str]:
    """
    Handle the Predict tab submission.

    Parameters
    ----------
    file_obj : gr.File value
        Uploaded CSV file path, or None.
    use_sample : bool
        If True, ignore file_obj and use the built-in sample.

    Returns
    -------
    results_df : pd.DataFrame
        Predictions table.
    shap_path : str
        Path to the SHAP plot PNG.
    summary_text : str
        Short textual summary for the info box.
    """
    global _RAG_INDEX

    if _MODEL is None:
        return (
            pd.DataFrame({"error": ["Model not loaded. Run training first."]}),
            None,
            "Model not loaded. Please run `python -m src.pipeline.train` to train the model.",
        )

    try:
        if use_sample or file_obj is None:
            df_raw = _SAMPLE_DF.copy()
            source = "built-in sample (20 rows)"
        else:
            df_raw = pd.read_csv(file_obj.name)
            source = f"uploaded file ({len(df_raw):,} rows)"

        results, proba, X = _predict(df_raw)

        n_high = int((proba > 0.7).sum())
        n_critical = int((proba > 0.85).sum())
        avg_prob = float(proba.mean())
        rev_at_risk = float(
            results.loc[proba > 0.7, "MonthlyCharges"].sum()
            if "MonthlyCharges" in results.columns else 0
        )

        summary = (
            f"Source: {source}\n"
            f"Customers scored: {len(results):,}\n"
            f"Average churn probability: {avg_prob:.1%}\n"
            f"High-risk customers (>70%): {n_high} ({n_high/max(len(results),1):.1%})\n"
            f"Critical-risk customers (>85%): {n_critical}\n"
            f"Monthly revenue at risk: ${rev_at_risk:,.0f}"
        )

        shap_path = _shap_plot(X, proba)

        # Lazily build RAG index for the Analyze tab
        if n_high > 0 and os.getenv("GROQ_API_KEY"):
            try:
                from src.rag.insight_rag import ChurnRAG
                high_risk_df = results[proba > 0.7].copy()
                _RAG_INDEX = ChurnRAG().build_churn_index(high_risk_df)
                logger.info("RAG index built with %d high-risk customers", n_high)
            except Exception as exc:  # noqa: BLE001
                logger.warning("RAG index build failed: %s", exc)

        # Return top-20 columns for readability
        display_cols = [
            c for c in [
                "customerID", "tenure", "Contract", "MonthlyCharges",
                "InternetService", "churn_probability", "risk_label",
            ]
            if c in results.columns
        ]
        return results[display_cols].head(100), shap_path, summary

    except Exception as exc:  # noqa: BLE001
        logger.exception("Prediction failed")
        return (
            pd.DataFrame({"error": [str(exc)]}),
            None,
            f"Error during prediction: {exc}",
        )


def analyze_tab_handler(question: str) -> str:
    """
    Handle the Analyze tab — answer natural-language questions via RAG + Groq.
    """
    if not question.strip():
        return "Please enter a question, e.g. 'Which contract types have the highest churn risk?'"

    if not os.getenv("GROQ_API_KEY"):
        return (
            "GROQ_API_KEY is not set.\n\n"
            "To enable AI-powered analysis:\n"
            "1. Get a free key at https://console.groq.com\n"
            "2. Add it to your .env file: GROQ_API_KEY=gsk_...\n"
            "3. Restart the app."
        )

    if _RAG_INDEX is None:
        return (
            "No customer index available yet.\n\n"
            "Please go to the Predict tab first and run a prediction — "
            "this builds the knowledge base that the Analyze tab queries."
        )

    try:
        from src.rag.insight_rag import ChurnRAG
        answer = ChurnRAG().query_churn_insights(_RAG_INDEX, question)
        return answer
    except Exception as exc:  # noqa: BLE001
        logger.exception("RAG query failed")
        return f"Analysis failed: {exc}"


