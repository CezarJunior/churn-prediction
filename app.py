# Core prediction logic
# ---------------------------------------------------------------------------

def _predict(df_raw: pd.DataFrame) -> pd.DataFrame:
    """
    Run the model on a raw dataframe and return the input with appended
    ``churn_probability`` and ``risk_label`` columns.
    """
    df_clean = clean_data(df_raw)
    df_feat = engineer_features(df_clean)
    X, _ = get_feature_target_split(df_feat)
    proba = _MODEL.predict_proba(X)[:, 1]

    result = df_raw.copy().reset_index(drop=True)
    result["churn_probability"] = (proba * 100).round(1)
    result["risk_label"] = pd.cut(
        proba,
        bins=[-0.001, 0.3, 0.5, 0.7, 1.001],
        labels=["Low", "Medium", "High", "Critical"],
    ).astype(str)
    return result, proba, X


def _shap_plot(X: pd.DataFrame, proba: np.ndarray) -> str:
    """
    Generate a SHAP bar plot for the top-15 features and save it to a
    temporary PNG file.  Returns the file path.
    """
    try:
        import shap

        clf = _MODEL.named_steps["classifier"]
        pre = _MODEL.named_steps["preprocessor"]
        X_transformed = pre.transform(X)

        try:
            feature_names = list(pre.get_feature_names_out())
        except Exception:
            feature_names = [f"f{i}" for i in range(X_transformed.shape[1])]

        explainer = shap.TreeExplainer(clf)
        shap_values = explainer.shap_values(X_transformed)

        # For binary classification shap_values may be 2D (samples × features)
        if isinstance(shap_values, list):
            sv = shap_values[1]
        else:
            sv = shap_values

        mean_abs = np.abs(sv).mean(axis=0)
        top_idx = np.argsort(mean_abs)[-15:][::-1]

        fig, ax = plt.subplots(figsize=(8, 5))
        colors = ["#e74c3c" if v > 0 else "#3498db" for v in mean_abs[top_idx]]
        ax.barh(
            [feature_names[i] if i < len(feature_names) else f"f{i}" for i in top_idx],
            mean_abs[top_idx],
            color=colors,
            edgecolor="none",
        )
        ax.set_xlabel("Mean |SHAP value|", fontsize=11)
        ax.set_title("Top 15 Feature Importances (SHAP)", fontsize=13, fontweight="bold")
        ax.invert_yaxis()
        plt.tight_layout()

        out_path = str(PROJECT_ROOT / "models" / "_shap_plot.png")
        fig.savefig(out_path, dpi=120, bbox_inches="tight")
        plt.close(fig)
        return out_path

    except Exception as exc:  # noqa: BLE001
        logger.warning("SHAP plot failed: %s", exc)
        # Return a simple placeholder plot
        fig, ax = plt.subplots(figsize=(6, 3))
        ax.text(
            0.5, 0.5, f"SHAP unavailable:\n{exc}",
            ha="center", va="center", transform=ax.transAxes, fontsize=10,
        )
        ax.axis("off")
        out_path = str(PROJECT_ROOT / "models" / "_shap_plot.png")
        fig.savefig(out_path, dpi=100)
        plt.close(fig)
        return out_path


