def build_ui() -> gr.Blocks:
    """Construct and return the Gradio Blocks app."""
    model_status = (
        "Model loaded successfully."
        if _MODEL is not None
        else "Model NOT loaded — run training first."
    )

    with gr.Blocks(
        title="Churn Prediction — Telecom",
        theme=gr.themes.Soft(),
    ) as demo:
        gr.Markdown(
            """
# Telecom Customer Churn Prediction
**ML + LLM Orchestration Portfolio Project**

Predict which customers are at risk of churning using an XGBoost model
tuned with Optuna, and analyse patterns with a RAG pipeline powered by
LlamaIndex + Groq's free LLM API.

---
"""
        )
        gr.Markdown(f"> **Status:** {model_status}")

        with gr.Tabs():
            # ── Tab 1: Predict ──────────────────────────────────────────────
            with gr.Tab("Predict"):
                gr.Markdown(
                    """
### Batch Churn Prediction

Upload a CSV with the same schema as the IBM Telco dataset, or use the
built-in 20-row sample to see the model in action.
"""
                )
                with gr.Row():
                    with gr.Column(scale=1):
                        file_input = gr.File(
                            label="Upload CSV (optional)",
                            file_types=[".csv"],
                        )
                        use_sample_cb = gr.Checkbox(
                            label="Use built-in sample data",
                            value=True,
                        )
                        predict_btn = gr.Button("Run Prediction", variant="primary")

                    with gr.Column(scale=2):
                        summary_box = gr.Textbox(
                            label="Summary",
                            lines=7,
                            interactive=False,
                        )

                results_table = gr.Dataframe(
                    label="Predictions (top 100 rows)",
                    wrap=True,
                )
                shap_image = gr.Image(
                    label="SHAP Feature Importances",
                    type="filepath",
                )

                predict_btn.click(
                    fn=predict_tab_handler,
                    inputs=[file_input, use_sample_cb],
                    outputs=[results_table, shap_image, summary_box],
                )

            # ── Tab 2: Analyze ──────────────────────────────────────────────
            with gr.Tab("Analyze"):
                gr.Markdown(
                    """
### Natural Language Churn Analysis

Ask questions about the high-risk customers identified in the Predict tab.
The answers are generated by a RAG pipeline (LlamaIndex + FAISS) and
synthesised by Groq's Llama-3.3-70B.

**Prerequisites:** Run a prediction first, then ask questions here.

**Example questions:**
- Which contract types are most common among high-risk customers?
- What is the typical tenure of customers most likely to churn?
- Do high-risk customers tend to use fiber optic internet?
"""
                )
                question_input = gr.Textbox(
                    label="Your question",
                    placeholder="Which customers are at the highest risk and why?",
                    lines=2,
                )
                analyze_btn = gr.Button("Analyze", variant="primary")
                answer_output = gr.Textbox(
                    label="Answer",
                    lines=15,
                    interactive=False,
                )

                analyze_btn.click(
                    fn=analyze_tab_handler,
                    inputs=[question_input],
                    outputs=[answer_output],
                )

        gr.Markdown(
            """
---
*Built with scikit-learn · XGBoost · Optuna · MLflow · LangGraph · LlamaIndex · LangChain · Groq · Gradio*
"""
        )

    return demo


